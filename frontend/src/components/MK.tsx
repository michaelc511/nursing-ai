import { useEffect, useState } from "react";
import { aiMode, AIMode } from "../api";

// "AI-MK" = mocked AI: prepared, simulated answers, NOT real AI. Used on every AI feature and the chat.
export const MK_TEXT = "AI-MK = mocked, not real AI";

export function useAIMode(): AIMode | null {
  const [m, setM] = useState<AIMode | null>(null);
  useEffect(() => { aiMode().then(setM); }, []);
  return m;
}

/** AI icon (sparkle). `busy` pulses while the AI is working. */
export function AIIcon({ busy = false, title = "Generated by AI (Claude)" }: { busy?: boolean; title?: string }) {
  return (
    <span className={busy ? "ai-icon busy" : "ai-icon"} title={title} aria-label={title} role="img">
      <svg viewBox="0 0 24 24" width="17" height="17" aria-hidden="true">
        <path d="M10 3c.6 3.9 2.6 5.9 6.5 6.5-3.9.6-5.9 2.6-6.5 6.5-.6-3.9-2.6-5.9-6.5-6.5C7.4 8.9 9.4 6.9 10 3z" fill="currentColor" />
        <path d="M18 13c.3 2 1.3 3 3.3 3.3-2 .3-3 1.3-3.3 3.3-.3-2-1.3-3-3.3-3.3 2-.3 3-1.3 3.3-3.3z" fill="currentColor" />
        <circle cx="18.5" cy="5" r="1.4" fill="currentColor" />
      </svg>
    </span>
  );
}

/** Tag on every AI output: yellow "AI-MK" in mock mode, the AI icon with real AI. */
export function MK({ busy = false }: { long?: boolean; busy?: boolean }) {
  const m = useAIMode();
  if (!m) return null;
  if (m.mode !== "mock") return <AIIcon busy={busy} />;
  return <span className={busy ? "mk busy" : "mk"} title="Mocked: a prepared, simulated answer. Not real AI.">AI-MK</span>;
}

/** Banner at the top of every screen in mock mode. */
export function MockBanner() {
  const m = useAIMode();
  if (m?.mode !== "mock") return null;
  return (
    <div className="mk-banner" role="note">
      <b>Mock AI mode.</b> Anything marked <span className="mk">AI-MK</span> is a prepared, simulated answer, <b>not real AI</b>.
      Real Claude replaces it next.
    </div>
  );
}
